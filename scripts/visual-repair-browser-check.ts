import { chromium, expect } from "@playwright/test";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { startApp } from "../src/service/server.ts";
import { VisualWorkspace } from "../src/service/visual-workspace.ts";
import { canonical, reference } from "../src/kernel/packets.ts";
import type { Selections, Specification } from "../src/modules/website/exploration-contracts.ts";
import { seedVisual, offlineVisualProviders, visualFixture } from "./visual-fixture.ts";

/** Synthetic browser assertions for draft isolation, exact source closures and requested controls. */
export async function checkVisualRepairs() {
  const evidence = resolve(process.env["BVE_EVIDENCE_DIR"] ?? "../v02-evidence");
  mkdirSync(evidence, { recursive: true });
  const root = mkdtempSync(join(tmpdir(), "bve-visual-repairs-"));
  let app = await startApp(root, 0, undefined, offlineVisualProviders);
  const seeded = await seedVisual(app.workspace), v = seeded.v, pid = seeded.p.project.id;
  const about = v.exploration.createWorkUnit(pid, { version: 1, pageType: "about", label: "About reference", source: "Synthetic" });
  const cross = await v.exploration.importCandidate(pid, reference(about), await visualFixture(5), "Synthetic rights");
  const homeCandidate = v.state(pid, reference(seeded.unit)).candidates[0]!;
  v.exploration.selections(pid, { version: 1, workUnit: reference(seeded.unit), entries: [homeCandidate, cross].map((c,i) => ({ id: i ? "cross-source" : "home-source", candidate: reference(c), integrity: c.integrity, image: c.payload.state.image, orientation: "encoded-top-left", coordinates: "normalized-original", anchor: { kind: "whole" }, intent: "inspiration", preservation: null, notes: [{ id: "note-"+i, text: "Saved source "+i, source: "Synthetic" }] })) });
  const other = v.create({ title: "Independent draft project" });
  v.exploration.createWorkUnit(other.project.id, { version: 1, pageType: "homepage", label: "Other Homepage", source: "Synthetic" });
  const browser = await chromium.launch({ headless: true, ...(process.env["BVE_CHROMIUM_EXECUTABLE"] ? { executablePath: process.env["BVE_CHROMIUM_EXECUTABLE"] } : {}), args: ["--no-sandbox", "--disable-dev-shm-usage"] });
  let context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  let page = await context.newPage();
  const errors: string[] = [], screenshots: string[] = [];
  const watch = () => { page.setDefaultTimeout(15000); page.on("pageerror", e => errors.push(e.message)); };
  watch();
  const idle = async () => { await expect(page.locator("#visual-app")).not.toHaveAttribute("aria-busy", "true"); };
  const source = async (id: string) => { await page.locator(`[data-entry="${id}"]`).click(); };
  const state = () => new VisualWorkspace(app.workspace).state(pid, reference(seeded.unit));
  const selections = () => state().records.find(p => (p.payload as { kind: string }).kind === "raster-selections")!.payload as { state: Selections };
  const specs = () => state().records.filter(p => (p.payload as { kind: string }).kind === "raster-specification").map(p => (p.payload as { state: Specification }).state);
  const lastSpec = () => specs().at(-1)!;
  const snapshot = () => canonical(app.workspace.kernel.ledger(pid));
  const shot = async (name: string) => { await page.screenshot({ path: join(evidence, name+".png") }); screenshots.push(name+".png"); expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true); };
  const freeze = async () => { await page.locator("#prepare button.primary").click(); await idle(); };
  const assertDraft = async () => {
    await expect(page.locator("#prepare [name=intent]")).toHaveValue("Keep my carefully specified intent");
    await expect(page.locator("#prepare [name=count]")).toHaveValue("6");
    await expect(page.locator("#prepare [name=direction]")).toHaveValue("follow");
    await expect(page.locator("#prepare [name=brand]")).toHaveValue("0");
  };
  try {
    await page.goto(app.origin+"/visual"); await idle();
    await page.locator("#project").selectOption(pid); await idle();
    await expect(page.locator(".candidate")).toHaveCount(6);
    await source("home-source");
    const initial = snapshot();
    await page.locator("#annotation textarea").fill("Keep this unsaved note");
    await page.locator("#prepare [name=intent]").fill("Keep my carefully specified intent");
    await page.locator("#prepare [name=count]").selectOption("6");
    await page.locator("#prepare [name=direction]").selectOption("follow");
    await page.locator("#brand-panel > summary").click();
    await page.locator("#prepare [name=brand]").selectOption("0");
    await page.locator("#level1-panel > summary").click();
    await page.locator("#tune-panel > summary").click();
    await expect(page.locator(".focus-view #level1-panel")).toBeVisible();
    await expect(page.locator("#request-scope")).toHaveValue("home-source");
    const density = page.getByRole("slider", { name: "Visual Density request", exact: true });
    await expect(density).toHaveAttribute("min", "1"); await expect(density).toHaveAttribute("max", "10");
    await expect(density).toHaveAttribute("aria-valuetext", "No request");
    await expect(page.locator("[data-number=visual-density]")).toHaveValue("");
    expect(snapshot()).toBe(initial); // opening panels creates no request/record
    await density.focus(); await page.keyboard.press("ArrowRight");
    await expect(page.locator("[data-number=visual-density]")).toHaveValue("1.1");
    await page.locator("[data-clear=visual-density]").click();
    await expect(page.locator("[data-number=visual-density]")).toHaveValue("");
    await page.locator("[data-number=visual-density]").fill("6.4");
    await page.locator("[data-number=contrast]").fill("2.7");
    await page.locator("[data-request=font]").fill("Synthetic Serif");
    await page.locator("[data-request=visual-effects-category]").selectOption("glow");
    await page.locator("[data-number=visual-effects-strength]").fill("8.3");
    expect(snapshot()).toBe(initial); // keyboard/numeric requests never call an executor
    await page.locator("#layout").selectOption("film");
    await assertDraft(); await expect(page.locator("#annotation textarea")).toHaveValue("Keep this unsaved note");
    await expect(page.locator("[data-number=visual-density]")).toHaveValue("6.4");
    await source("cross-source");
    await expect(page.locator(".focus-toolbar")).toContainText("About reference · v1");
    await page.locator("#annotation textarea").fill("Cross-page independent note");
    await page.locator("[data-request=spacing]").fill("88");
    await page.locator("#annotation button").first().click(); await idle();
    await source("home-source");
    await expect(page.locator("#annotation textarea")).toHaveValue("Keep this unsaved note");
    await page.locator("[data-open]").nth(1).click();
    await page.locator("[data-compare]").first().click(); await page.locator("[data-compare]").nth(1).click();
    await page.locator("#zoom").selectOption("1.5");
    await source("home-source");
    await assertDraft(); await expect(page.locator("[data-number=visual-density]")).toHaveValue("6.4");
    await expect(page.locator("#annotation textarea")).toHaveValue("Keep this unsaved note");
    await page.locator("#page").selectOption(about.id+":1"); await idle();
    await expect(page.locator("#prepare [name=intent]")).toHaveValue("");
    await page.locator("#prepare [name=intent]").fill("About-only unsaved intent");
    await page.locator("#page").selectOption(seeded.unit.id+":1"); await idle(); await source("home-source"); await assertDraft();
    await page.locator("#project").selectOption(other.project.id); await idle();
    await expect(page.locator("#prepare [name=intent]")).toHaveValue("");
    await page.locator("#prepare [name=intent]").fill("Other-project draft");
    await page.locator("#project").selectOption(pid); await idle(); await source("home-source"); await assertDraft();
    await expect(page.locator("#annotation textarea")).toHaveValue("Keep this unsaved note");
    await page.route("**/api/v1/visual/prepare", async route => { await route.fulfill({ status: 409, contentType: "application/json", body: JSON.stringify({ error: "Synthetic preparation rejection" }) }); await page.unroute("**/api/v1/visual/prepare"); });
    const beforeRejected = specs().length; await freeze();
    await expect(page.locator("#visual-notice")).toContainText("Synthetic preparation rejection");
    expect(specs()).toHaveLength(beforeRejected); await assertDraft();
    await expect(page.locator("#annotation textarea")).toHaveValue("Keep this unsaved note");
    await page.locator("#annotation button").first().click(); await idle();
    await freeze(); await assertDraft();
    expect(lastSpec().metricRequests.find(m=>m.key==="home-source--visual-density")!.value).toBe(6.4);
    expect(lastSpec().metricRequests.find(m=>m.key==="home-source--visual-effects-category")!.value).toBe("glow");
    expect(lastSpec().metricRequests.find(m=>m.key==="home-source--visual-effects-strength")!.value).toBe(8.3);
    expect(lastSpec().constraints).toContainEqual({ path: "request.cross-source--spacing", value: 88 });
    expect(lastSpec().constraints).toContainEqual({ path: "request.home-source--contrast", value: 2.7 });
    expect(lastSpec().selectionSnapshot!.entries[1]!.candidate).toEqual(reference(cross));
    await page.locator(".focus-view").scrollIntoViewIfNeeded(); await shot("08-r123-b-desktop");
    await page.locator("#tune-panel [data-request=visual-effects]").scrollIntoViewIfNeeded(); await shot("12-r3-effects-desktop");
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator("#tune-panel [data-request=visual-effects]").scrollIntoViewIfNeeded(); await shot("13-r3-effects-narrow");
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.locator("[data-request=visual-effects-category]").selectOption(""); await freeze();
    expect(lastSpec().metricRequests.some(m=>m.key.endsWith("--visual-effects-category"))).toBe(false);
    expect(lastSpec().metricRequests.find(m=>m.key.endsWith("--visual-effects-strength"))!.value).toBe(8.3);
    await page.locator("[data-clear=visual-effects-strength]").click();
    await page.locator("[data-request=visual-effects-category]").selectOption("none"); await freeze();
    expect(lastSpec().metricRequests.some(m=>m.key.endsWith("--visual-effects-strength"))).toBe(false);
    expect(lastSpec().metricRequests.find(m=>m.key.endsWith("--visual-effects-category"))!.value).toBe("none");
    await page.locator("#annotation textarea").fill("Dirty removal note");
    const beforeRemoval = snapshot();
    await page.locator("#remove-entry").click();
    await expect(page.locator("#confirm-remove")).toBeVisible(); expect(snapshot()).toBe(beforeRemoval);
    await page.locator("#cancel-remove").click(); await expect(page.locator("#annotation textarea")).toHaveValue("Dirty removal note");
    await page.locator("#remove-entry").click(); await page.locator("#confirm-remove").click(); await idle();
    await freeze();
    expect(lastSpec().metricRequests.some(m=>m.key.endsWith("--visual-density"))).toBe(false);
    expect(lastSpec().constraints).toContainEqual({ path: "request.cross-source--spacing", value: 88 });
    expect(lastSpec().constraints.some(m=>m.path.startsWith("request.page--"))).toBe(false);
    await source("cross-source");
    await page.locator("#layout").selectOption("sheet"); await page.locator(".contact-sheet").scrollIntoViewIfNeeded(); await shot("09-r123-a-desktop");
    await page.locator("#layout").selectOption("film"); await page.setViewportSize({ width: 390, height: 844 }); await page.locator(".focus-view").scrollIntoViewIfNeeded(); await shot("10-r123-b-narrow");
    await page.locator("#layout").selectOption("sheet"); await page.locator(".contact-sheet").scrollIntoViewIfNeeded(); await shot("11-r123-a-narrow");
    await v.exploration.importCandidate(pid, reference(about), await visualFixture(4), "Synthetic rights", "imported", reference(cross));
    expect(state().candidates).toHaveLength(6); expect(selections().state.entries[0]!.candidate).toEqual(reference(cross));
    const persisted = canonical(state().records);
    await context.close(); await app.close(); app = await startApp(root, 0, undefined, offlineVisualProviders);
    context = await browser.newContext({ viewport: { width: 1440, height: 900 } }); page = await context.newPage(); watch();
    await page.goto(app.origin+"/visual"); await idle(); await page.locator("#project").selectOption(pid); await idle();
    expect(canonical(state().records)).toBe(persisted);
    for (const layout of ["sheet","film"]) { await page.locator("#layout").selectOption(layout); await source("cross-source"); await expect(page.locator("#annotation textarea")).toHaveValue("Cross-page independent note"); await expect(page.locator(".focus-toolbar")).toContainText("About reference · v1"); }
    await expect(page.locator("#prepare [name=intent]")).toHaveValue(""); // explicit session boundary
    await page.locator("#prepare [name=intent]").fill("Discard explicitly");
    page.once("dialog", dialog=>dialog.accept()); await page.locator("#discard-draft").click();
    await expect(page.locator("#prepare [name=intent]")).toHaveValue(""); expect(canonical(state().records)).toBe(persisted);
    // A corrupt closure produces an explicit unavailable view, never stale cards/actions.
    writeFileSync(join(app.workspace.assets.root, cross.payload.state.image.id), Buffer.from("corrupt"));
    await page.locator("#page").selectOption(about.id+":1"); await idle();
    await expect(page.locator(".workspace-error")).toContainText("Workspace unavailable");
    await expect(page.locator(".candidate")).toHaveCount(0); await expect(page.locator("#prepare")).toHaveCount(0);
    expect(errors).toEqual([]);
    const receipt = { check: "visual-r123", candidate: process.env["BVE_CANDIDATE_COMMIT"] ?? "working-tree", browser: browser.version(), platform: process.platform, draftViewRetention: true, pageProjectIsolation: true, rejectionRecovery: true, explicitDirtyRemoval: true, crossPageReopen: true, membershipIndependent: true, originalVersionPinned: true, semanticSliderKeyboardUnset: true, independentEffects: true, exactFrozenScopes: true, corruptWorkspaceExplicit: true, screenshots, errors, actualModelCalls: 0, actualImageProviderCalls: 0 };
    writeFileSync(join(evidence, "repairs.json"), JSON.stringify(receipt,null,2)); console.log(JSON.stringify(receipt));
  } finally { await browser.close(); await app.close(); rmSync(root,{recursive:true,force:true}); }
}
